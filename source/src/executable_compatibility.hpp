#pragma once
#include <windows.h>
#include <cstdint>
#include <cstring>

namespace MK9TradeFix {
    inline bool g_ExecutableAccepted = false;

    // A narrow allowlist for the executable observed during runtime validation.
    // PE identity plus original bytes at critical patch sites; not a full-file hash.
    inline bool ValidateExecutableImage(uintptr_t image, bool displayAlreadyPatched = false) {
        struct Site { uintptr_t address; unsigned char bytes[16]; };
        static const Site sites[] = {
        { 0x005691EB, { 0x0F, 0x84, 0x62, 0x01, 0x00, 0x00, 0x57, 0xE8, 0x79, 0x30, 0xFC, 0xFF, 0x8B, 0xF8, 0xE8, 0xA2 } },
        { 0x005692F7, { 0x73, 0x59, 0xA1, 0x28, 0x3D, 0xE5, 0x00, 0x2B, 0x05, 0x24, 0x3D, 0xE5, 0x00, 0x33, 0xFF, 0xC1 } },
        { 0x0058C4F5, { 0x0F, 0x83, 0xCF, 0x00, 0x00, 0x00, 0x0F, 0xAF, 0xCA, 0x80, 0x3D, 0x3C, 0x99, 0xDE, 0x00, 0x00 } },
        { 0x0071C090, { 0x8B, 0x55, 0x08, 0x8B, 0x4C, 0x13, 0x40, 0x0F, 0xB6, 0xB1, 0xE0, 0xDA, 0xDE, 0x00, 0x8D, 0x44 } },
        { 0x0071C5B6, { 0x8B, 0x40, 0x04, 0x89, 0x46, 0x04, 0x8B, 0x10, 0x89, 0x45, 0xFC, 0x89, 0x4D, 0xF8, 0x8D, 0x44 } },
        { 0x00A66AEA, { 0x8B, 0x4C, 0x24, 0x08, 0x85, 0xC9, 0x74, 0x0C, 0x8B, 0x11, 0x8B, 0x44, 0x24, 0x0C, 0x8B, 0x52 } },
        { 0x008AB040, { 0x55, 0x8B, 0xEC, 0x83, 0xEC, 0x10, 0x56, 0x8B, 0xF1, 0x56, 0xE8, 0x81, 0x2A, 0xB9, 0xFF, 0x83 } },
        { 0x008A5490, { 0x55, 0x8B, 0xEC, 0x83, 0xEC, 0x0C, 0x53, 0x56, 0x57, 0x8B, 0x7D, 0x0C, 0x8B, 0x9F, 0x38, 0x76 } },
        { 0x00895962, { 0x05, 0x64, 0x0C, 0x00, 0x00, 0xFF, 0x00, 0x8B, 0x75, 0x14, 0x8B, 0x16, 0xF6, 0x02, 0x08, 0x75 } },
        { 0x008B536B, { 0x8B, 0x97, 0xD0, 0x01, 0x00, 0x00, 0x8D, 0x45, 0xCC, 0xC1, 0xEA, 0x02, 0x50, 0x8D, 0x4D, 0xC0 } },
        { 0x004025A0, { 0x53, 0x8B, 0xDC, 0x83, 0xEC, 0x08, 0x83, 0xE4, 0xF0, 0x83, 0xC4, 0x04, 0x55, 0x8B, 0x6B, 0x04 } },
        };
        __try {
            const auto dos = reinterpret_cast<const IMAGE_DOS_HEADER*>(image);
            if (dos->e_magic != IMAGE_DOS_SIGNATURE || dos->e_lfanew <= 0 || dos->e_lfanew > 0x1000) return false;
            const auto pe = reinterpret_cast<const IMAGE_NT_HEADERS32*>(image + dos->e_lfanew);
            if (pe->Signature != IMAGE_NT_SIGNATURE || pe->FileHeader.Machine != IMAGE_FILE_MACHINE_I386 ||
                pe->FileHeader.TimeDateStamp != 0x53DBF399 || pe->OptionalHeader.Magic != IMAGE_NT_OPTIONAL_HDR32_MAGIC ||
                pe->OptionalHeader.SizeOfImage != 0x00CAE000 || pe->OptionalHeader.AddressOfEntryPoint != 0x0058CB8F ||
                pe->OptionalHeader.CheckSum != 0x00ADE631 || pe->OptionalHeader.ImageBase != 0x00400000) return false;
            for (const auto& site : sites) {
                unsigned char expected[16];
                memcpy(expected, site.bytes, sizeof(expected));
                if (displayAlreadyPatched) {
                    if (site.address == 0x005691EB) memset(expected, 0x90, 6);
                    if (site.address == 0x005692F7) memset(expected, 0x90, 2);
                    if (site.address == 0x0058C4F5) {
                        const unsigned char patch[] = {0xE9, 0xC7, 0, 0, 0, 0x90};
                        memcpy(expected, patch, sizeof(patch));
                    }
                }
                if (memcmp(reinterpret_cast<const void*>(image + site.address - 0x00400000), expected, sizeof(expected)) != 0) return false;
            }
            return true;
        } __except (EXCEPTION_EXECUTE_HANDLER) { return false; }
    }

    inline bool ValidateExecutable(bool displayAlreadyPatched = false) {
        const auto image = reinterpret_cast<uintptr_t>(GetModuleHandleW(nullptr));
        return image == 0x00400000 && ValidateExecutableImage(image, displayAlreadyPatched);
    }
}
